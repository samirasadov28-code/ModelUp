/**
 * Native JS Excel generator — replaces the Python excel-service entirely.
 *
 * Builds a multi-sheet .xlsx from a ModelOutputs object using ExcelJS.
 * Runs in Node (serverless-friendly) — no Python, no source-model files,
 * no Railway/Fly deployment required.
 */

import ExcelJS from "exceljs";
import type { ModelOutputs, QuestionnaireAnswers } from "./types";

const HEADER_FILL: ExcelJS.Fill = {
  type: "pattern",
  pattern: "solid",
  fgColor: { argb: "FF2563EB" },
};

const SUBHEADER_FILL: ExcelJS.Fill = {
  type: "pattern",
  pattern: "solid",
  fgColor: { argb: "FFF3F4F6" },
};

const HEADER_FONT: Partial<ExcelJS.Font> = {
  bold: true,
  color: { argb: "FFFFFFFF" },
  size: 11,
};

const TITLE_FONT: Partial<ExcelJS.Font> = {
  bold: true,
  size: 14,
  color: { argb: "FF111827" },
};

const CURRENCY_FMT = '"$"#,##0';
const CURRENCY_FMT_2 = '"$"#,##0.00';
const PERCENT_FMT = "0.0%";
const NUMBER_FMT = "#,##0";

function styleHeaderRow(row: ExcelJS.Row): void {
  row.eachCell((cell) => {
    cell.fill = HEADER_FILL;
    cell.font = HEADER_FONT;
    cell.alignment = { vertical: "middle", horizontal: "center" };
    cell.border = {
      bottom: { style: "thin", color: { argb: "FF1E3A8A" } },
    };
  });
  row.height = 22;
}

function styleSectionTitle(cell: ExcelJS.Cell): void {
  cell.font = TITLE_FONT;
  cell.alignment = { vertical: "middle" };
}

function autoFitColumns(ws: ExcelJS.Worksheet, minWidth = 12, maxWidth = 32): void {
  ws.columns.forEach((col) => {
    let max = minWidth;
    col.eachCell?.({ includeEmpty: false }, (cell) => {
      const val = cell.value == null ? "" : String(cell.value);
      max = Math.max(max, Math.min(maxWidth, val.length + 2));
    });
    col.width = max;
  });
}

